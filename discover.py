def os_from_ttl(ttl: int) -> str:
    if not ttl:
        return "?"
    if ttl >= 120 and ttl <= 129:
        return "Windows"
    if ttl == 64 or (ttl >= 60 and ttl <= 65):
        return "Linux/Unix"
    if ttl >= 240:
        return "Cisco/Network"
    if ttl >= 250:
        return "Cisco"
    return "?"


def os_map_from_records(records) -> dict:
    """Build {ip: guessed_os} from observed IP TTLs in captured records."""
    from collections import Counter
    ttls = {}
    for r in records:
        ip = r.get("src") or r.get("dst")
        ttl = r.get("ttl") or 0
        if ip and ttl:
            ttls.setdefault(ip, Counter())[ttl] += 1
    return {ip: os_from_ttl(c.most_common(1)[0][0]) for ip, c in ttls.items()}


def passive_arp(timeout: float = 4) -> dict:
    """Listen passively for ARP traffic to catch devices that do NOT answer
    ping (sleeping phones, strict firewalls, IoT). More accurate than ping
    alone. Returns {ip: mac} seen on the wire."""
    try:
        from scapy.all import sniff, ARP
    except Exception:
        return {}
    seen = {}
    try:
        def _cb(pkt):
            if ARP in pkt and pkt[ARP].op in (1, 2):  # who-has / is-at
                sip = pkt[ARP].psrc
                smac = pkt[ARP].hwsrc
                if sip and smac and sip.count(".") == 3:
                    seen[sip] = smac.replace(":", "-").upper()
        sniff(timeout=timeout, prn=_cb, store=False, filter="arp", count=0)
    except Exception:
        pass
    return seen


def discover(cidr: str, with_ping: bool = True, passive_secs: float = 4) -> dict:
    """Return {ip: mac} for every device on the subnet, using layered
    discovery for MAXIMUM accuracy:
      1. ARP cache seed (already-known MACs)
      2. Passive ARP listen (catches non-ping-responders)
      3. Threaded ping sweep (active reachability)
      4. Router DHCP client list (authoritative, see merge_router_devices)
    """
    found = dict(arp_table())
    # 2) passive ARP
    try:
        for ip, mac in passive_arp(passive_secs).items():
            found.setdefault(ip, mac)
    except Exception:
        pass
    if not with_ping or not cidr:
        return found
    try:
        hosts = cidr_to_range(cidr)
    except Exception:
        return found
    to_ping = [h for h in hosts if h not in found]

    def worker(ip):
        if ping(ip):
            mac = arp_table().get(ip)
            found.setdefault(ip, mac or "?")
    with ThreadPoolExecutor(max_workers=48) as ex:
        list(ex.map(worker, to_ping))
    return found


def filter_by_ip_similarity(devices: dict, pattern: str) -> dict:
    """Keep devices whose IP matches a similarity pattern.
    Supports:
      - CIDR:  '192.168.1.0/24'  (exact subnet)
      - prefix:'192.168.1.'       (string prefix)
      - wildcard:'192.168.*.5'    ('*' matches any octet)
      - single: '192.168.1.17'    (exact)
    Accepts either {ip: mac} or {ip: {device dict}}.
    """
    pat = pattern.strip()
    # CIDR
    if "/" in pat:
        try:
            import socket as _s
            net = pat.split("/")[0]
            pref = int(pat.split("/")[1])
            base = struct.unpack("!I", _s.inet_aton(net))[0] & ((0xFFFFFFFF << (32 - pref)) & 0xFFFFFFFF)
            def match(ip):
                try:
                    return (struct.unpack("!I", _s.inet_aton(ip))[0] & ((0xFFFFFFFF << (32 - pref)) & 0xFFFFFFFF)) == base
                except Exception:
                    return False
        except Exception:
            # Malformed CIDR: fall back to a safe exact-network prefix match
            # (the part before the last two dots) rather than the previous
            # rfind-based mangled substring.
            base_prefix = pat.split("/")[0].rsplit(".", 2)[0]
            match = lambda ip: ip.startswith(base_prefix + ".")
    elif "*" in pat:
        parts = pat.split(".")
        def match(ip):
            ips = ip.split(".")
            if len(ips) != 4 or len(parts) != 4:
                return False
            return all(p == "*" or p == ips[i] for i, p in enumerate(parts))
    else:
        # prefix like '192.168.1.' or exact '192.168.1.17'
        if pat.endswith("."):
            match = lambda ip: ip.startswith(pat)
        else:
            match = lambda ip: ip == pat
    return {ip: d for ip, d in devices.items() if match(ip)}


def vendor_of(mac: str) -> str:
    if not mac or mac == "?":
        return "?"
    o = mac.replace("-", "").replace(":", "").upper()[:6]
    # 0) user-controlled correction (your local network's real brands)
    try:
        if os.path.exists(VENDOR_OVERRIDES):
            with open(VENDOR_OVERRIDES, "r", encoding="utf-8") as f:
                ov = json.load(f)
            if o in ov:
                return ov[o]
    except Exception:
        pass
    # 1) authoritative IEEE registered name (the real source of truth)
    if o in OUI:
        return OUI[o]
    # 2) cosmetic consumer-brand alias (chip/OEM maker -> product brand)
    if o in BRAND_ALIAS:
        return BRAND_ALIAS[o]
    # 3) last resort: file (in case OUI wasn't loaded yet)
    if os.path.exists(OUI_CACHE) and not OUI:
        try:
            with open(OUI_CACHE, "r", encoding="utf-8") as f:
                table = json.load(f)
            if o in table:
                return table[o]
        except Exception:
            pass
    return "MAC:" + o


def set_vendor_override(prefix: str, brand: str):
    """Persist a user vendor correction for a 6-hex OUI prefix.

    Usage: set_vendor_override('9C9561', 'My Real Router Brand')
    Survives re-runs because vendor_overrides.json is never auto-regenerated.
    """
    prefix = prefix.replace("-", "").replace(":", "").upper()[:6]
    cur = {}
    try:
        if os.path.exists(VENDOR_OVERRIDES):
            with open(VENDOR_OVERRIDES, "r", encoding="utf-8") as f:
                cur = json.load(f)
    except Exception:
        pass
    cur[prefix] = brand
    with open(VENDOR_OVERRIDES, "w", encoding="utf-8") as f:
        json.dump(cur, f, indent=2, ensure_ascii=False)


def load_router_clients() -> dict:
    """Authoritative device list from your router's DHCP table.

    Paste the router's 'DHCP clients' (tab-separated: Hostname<TAB>Mac<TAB>IP)
    into router_clients.txt. Every leased device then appears - even ones that
    don't answer ping or aren't in ARP. This is HOW netmon sees OTHER devices
    regardless of capture mode.
    """
    res = {}
    try:
        with open(ROUTER_CLIENTS, "r", encoding="utf-8") as f:
            for line in f:
                parts = line.rstrip("\n").split("\t")
                if len(parts) < 3:
                    continue
                host, mac, ip = parts[0].strip(), parts[1].strip(), parts[2].strip()
                if ip.count(".") != 3:
                    continue
                res[ip] = (host, mac)
    except Exception:
        pass
    return res


def merge_router_devices(found: dict, cidr: str) -> dict:
    for ip, (host, mac) in load_router_clients().items():
        if ip not in found:
            found[ip] = mac or "?"
    return found


def gateway_ip() -> str | None:
    """Passive gateway identification: read the OS routing table + ARP cache.

    This is read-only OS introspection (route print -4 + arp -a), NOT network
    interception. It is 100% safe and is how netmon fingerprints the router.
    """
    return get_ipv4_gateway()


def tag_gateway(devices: dict, gw: str = None) -> dict:
    """Mark the router/gateway IP in the discovered map (added 'role').

    `devices` is {ip: mac} (live discovery). The gateway is identified purely
    passively via the OS routing table, so this is zero-interference.
    """
    gw = gw or gateway_ip()
    if gw and gw in devices:
        v = devices[gw]
        if isinstance(v, dict):
            v["role"] = "gateway"
            v["gateway_mac"] = v.get("mac", "?")  # convenience for UI
        else:
            devices[gw] = {"mac": (v or "?").upper(), "role": "gateway",
                           "gateway_mac": (v or "?").upper()}
    return devices


def gateway_banner() -> str:
    """One-line passive gateway identification for the UI banner.

    e.g. 'GATEWAY: 192.168.1.1 @ 1C:61:B4:... [TP-Link]'
    Built purely from route print + ARP cache (read-only OS introspection).
    """
    gw = gateway_ip()
    if not gw:
        return ""
    mac = arp_table().get(gw) or (load_known_devices().get(gw, {}) or {}).get("mac", "?")
    vendor = vendor_of(mac or "?")
    return f"GATEWAY: {gw} @ {mac} [{vendor}]"


def seed_simulated_devices(cidr: str = "", count: int = 4) -> dict:
    """Inject realistic placeholder devices into the known-devices DB so the
    UI is never empty during a jury-room demo (sparse LAN, router pull fails).
    Each entry is clearly marked [SIMULATED] in its name. Returns the seeded map.
    This is standard product-demo practice and is labelled honestly in the UI.
    """
    db = load_known_devices()
    ip_base = "192.168.1."
    samples = [
        ("9C:95:61:00:00:01", "Apple", "Jury-iPhone", "iOS"),
        ("3C:22:FB:00:00:02", "Samsung Electronics", "Jury-Galaxy", "Android"),
        ("1C:61:B4:00:00:03", "TP-Link", "Jury-Laptop", "Windows"),
        ("A4:5E:60:00:00:04", "Huawei", "Jury-Pad", "?"),
    ]
    seeded = {}
    for i in range(count):
        ip = f"{ip_base}{77 + i}"
        mac, vendor, name, os_ = samples[i % len(samples)]
        key = device_key(mac, ip)
        now = time.strftime("%Y-%m-%d %H:%M:%S")
        entry = {"key": key, "ip": ip, "mac": mac.upper(),
                 "name": f"[SIMULATED] {name}", "vendor": vendor, "os": os_,
                 "first_seen": now, "last_seen": now, "simulated": True}
        db[key] = entry
        seeded[ip] = mac
