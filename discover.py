def run(cmd: str, timeout: float = 8) -> str:
    try:
        p = subprocess.run(cmd, shell=True, capture_output=True, timeout=timeout, text=True)
        return p.stdout or ""
    except Exception as e:
        return f"__ERR__{e}"


def _field(val: str) -> str:
    return val.split(":", 1)[1].strip().split("(")[0].strip() if ":" in val else val.strip()


def mask_to_prefix(mask: str) -> int:
    try:
        m = struct.unpack("!I", socket.inet_aton(mask))[0]
        return bin(m).count("1")
    except Exception:
        return 24

def cidr_to_range(cidr: str):
    ip, pref = cidr.split("/")
    pref = int(pref)
    netint = struct.unpack("!I", socket.inet_aton(ip))[0]
    mask = (0xFFFFFFFF << (32 - pref)) & 0xFFFFFFFF
    net = netint & mask
    bcast = net | (~mask & 0xFFFFFFFF)
    return [socket.inet_ntoa(struct.pack("!I", i)) for i in range(net + 1, bcast)]


def get_ipv4_gateway() -> str | None:
    out = run("route print -4", timeout=8)
    for line in out.splitlines():
        f = line.split()
        if len(f) >= 3 and f[0] == "0.0.0.0" and f[1] == "0.0.0.0":
            g = f[2]
            if g not in ("On-link", "0.0.0.0", ""):
                return g
    return None


def detect_self():
    ip = None
    try:
        s = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
        s.connect(("8.8.8.8", 80))
        ip = s.getsockname()[0]
        s.close()
    except Exception:
        pass
    out = run("ipconfig /all", timeout=12)
    adapters = []
    cur = None
    for raw in out.splitlines():
        line = raw.rstrip()
        if not line.strip():
            continue
        stripped = line.strip()
        if not raw.startswith(" ") and stripped.endswith(":"):
            name = stripped.rstrip(":").replace(" adapter", "").strip()
            cur = {"name": name, "ip": None, "mask": None, "gw": None, "mac": None}
            adapters.append(cur)
            continue
        if cur is None:
            continue
        low = stripped.lower()
        if low.startswith("ipv4 address"):
            cur["ip"] = _field(stripped)
        elif "subnet mask" in low:
            cur["mask"] = _field(stripped)
        elif "physical address" in low or "mac address" in low:
            cur["mac"] = _field(stripped)
    if not ip:
        ip = adapters[0]["ip"] if adapters else None
    chosen = next((a for a in adapters if a["ip"] == ip), None) or (adapters[0] if adapters else None)
    iface = chosen["name"] if chosen else None
    netmask = chosen["mask"] if chosen else None
    # Prefer the real IPv4 gateway from the routing table (not ipconfig's
    # IPv6 link-local line, which breaks ARP-spoof / whole-LAN).
    gw = get_ipv4_gateway()
    cidr = None
    if ip and netmask:
        try:
            cidr = f"{ip}/{mask_to_prefix(netmask)}"
        except Exception:
            cidr = None
    return ip, netmask, iface, gw, cidr


def netbios_name(ip: str) -> str:
    """Resolve a device's NetBIOS/host name (Windows LAN). Returns '' if none."""
    out = run(f"nbtstat -A {ip}", timeout=4)
    for line in out.splitlines():
        s = line.strip()
        # <00> ... UNIQUE / GROUP lines carry the name in column 1
        if "<00>" in s and "UNIQUE" in s:
            name = s.split("<00>")[0].strip()
            if name and name not in ("", "MSOFFICE", "WORKGROUP"):
                return name
    return ""


def resolve_name(ip: str) -> str:
    """Best-effort device name: NetBIOS first, then reverse DNS (fast timeout)."""
    n = netbios_name(ip)
    if n:
        return n
    try:
        socket.setdefaulttimeout(1.5)
        return socket.gethostbyaddr(ip)[0]
    except Exception:
        return ""


def ping(ip: str) -> bool:
    try:
        p = subprocess.run([r"C:\Windows\System32\ping.exe", "-n", "1", "-w", "500", ip],
                            stdout=subprocess.PIPE, stderr=subprocess.PIPE, timeout=2, check=False)
        return p.returncode == 0
    except Exception:
        return False


def arp_table() -> dict:
    out = run("arp -a", timeout=8)
    res = {}
    for line in out.splitlines():
        parts = line.split()
        if len(parts) >= 2 and parts[0].count(".") == 3:
            ip, mac = parts[0], parts[1]
            if mac in ("", "ff-ff-ff-ff-ff-ff", "00-00-00-00-00-00"):
                continue
            if ip.startswith(("224.", "239.", "255.")):
                continue
            res[ip] = mac
    return res


